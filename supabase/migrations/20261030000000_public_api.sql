-- Website Assistant: public API keys and domain lock
--
-- api_keys              One publishable key per client (pk_live_...), used by
--                       the website widget to call the public chat API.
-- allowed_domains       Websites allowed to use a client's key.
-- clients (new columns) Pause switch, test mode and monthly message limit.
-- rate_limit_buckets    Request counters for rate limiting (server only).
-- public_api_rejections Log of rejected public requests, for each client.
--
-- Safe to run in the Supabase SQL Editor or with `supabase db push`.

create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------------------
-- Assistant settings on the client record
-- ---------------------------------------------------------------------------

alter table public.clients
  add column if not exists assistant_paused boolean not null default false,
  add column if not exists test_mode boolean not null default false,
  add column if not exists monthly_message_limit integer not null default 1000;

alter table public.clients drop constraint if exists clients_monthly_message_limit_positive;
alter table public.clients
  add constraint clients_monthly_message_limit_positive check (monthly_message_limit >= 0);

-- Clients can switch their assistant off and on, and toggle test mode. The
-- monthly limit is part of their plan, so only the server can change it.
grant update (assistant_paused, test_mode) on table public.clients to authenticated;

-- ---------------------------------------------------------------------------
-- Conversations: where each message came from
-- ---------------------------------------------------------------------------

alter table public.conversations
  add column if not exists channel text not null default 'test';

alter table public.conversations drop constraint if exists conversations_channel_valid;
alter table public.conversations
  add constraint conversations_channel_valid check (channel in ('test', 'website'));

-- Counting this month's website messages per client.
create index if not exists conversations_client_created_idx
  on public.conversations (client_id, created_at)
  where channel = 'website';

-- ---------------------------------------------------------------------------
-- API keys
--
-- The key is a publishable identifier, like a payment provider's publishable
-- key: it is meant to sit in the client's website code, and it is useless on
-- any website that is not on the client's allowed list. It is generated by
-- the database from 192 random bits and can be rotated at any time.
-- ---------------------------------------------------------------------------

create or replace function public.generate_public_key()
returns text
language sql
volatile
set search_path = ''
as $$
  select 'pk_live_' || translate(encode(extensions.gen_random_bytes(24), 'base64'), '+/', '-_');
$$;

revoke all on function public.generate_public_key() from public, anon, authenticated;

create table if not exists public.api_keys (
  client_id uuid primary key references public.clients (id) on delete cascade,
  public_key text not null unique default public.generate_public_key(),
  -- Requests per minute across all visitors of this client's website.
  requests_per_minute integer not null default 60,
  created_at timestamptz not null default now(),
  regenerated_at timestamptz,

  constraint api_keys_public_key_format check (public_key ~ '^pk_live_[A-Za-z0-9_-]{32}$'),
  constraint api_keys_requests_per_minute_valid check (requests_per_minute between 1 and 10000)
);

comment on table public.api_keys is 'Publishable key per client for the public chat API.';

revoke all on table public.api_keys from anon, authenticated;
grant select (public_key, requests_per_minute, created_at, regenerated_at) on table public.api_keys to authenticated;

alter table public.api_keys enable row level security;

drop policy if exists "Clients can view their own API key" on public.api_keys;
create policy "Clients can view their own API key"
  on public.api_keys for select
  to authenticated
  using (client_id in (select id from public.clients where user_id = (select auth.uid())));

-- Replaces the signed-in client's key. The old key stops working at once.
create or replace function public.regenerate_public_key()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.api_keys
  set public_key = public.generate_public_key(), regenerated_at = now()
  where client_id in (select id from public.clients where user_id = auth.uid());

  if not found then
    raise exception 'No API key found for this account';
  end if;
end;
$$;

revoke all on function public.regenerate_public_key() from public, anon;
grant execute on function public.regenerate_public_key() to authenticated;

-- ---------------------------------------------------------------------------
-- Allowed domains
--
-- "myclinic.com" covers myclinic.com and www.myclinic.com. With
-- include_subdomains it also covers any subdomain (*.myclinic.com).
-- "localhost" is only honoured while the client's test mode is on.
-- ---------------------------------------------------------------------------

create table if not exists public.allowed_domains (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.clients (id) on delete cascade,
  domain text not null,
  include_subdomains boolean not null default false,
  created_at timestamptz not null default now(),

  constraint allowed_domains_unique unique (client_id, domain),
  constraint allowed_domains_format check (
    domain = 'localhost'
    or (
      char_length(domain) <= 253
      and domain !~ '^www\.'
      and domain !~ '\.localhost$'
      and domain ~ '^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+([a-z]{2,63}|xn--[a-z0-9-]{1,59})$'
    )
  )
);

comment on table public.allowed_domains is 'Websites allowed to use a client''s public key.';

create index if not exists allowed_domains_client_idx on public.allowed_domains (client_id);

revoke all on table public.allowed_domains from anon, authenticated;
grant select on table public.allowed_domains to authenticated;
grant insert (client_id, domain, include_subdomains) on table public.allowed_domains to authenticated;
grant delete on table public.allowed_domains to authenticated;

alter table public.allowed_domains enable row level security;

drop policy if exists "Clients can view their own allowed domains" on public.allowed_domains;
create policy "Clients can view their own allowed domains"
  on public.allowed_domains for select
  to authenticated
  using (client_id in (select id from public.clients where user_id = (select auth.uid())));

drop policy if exists "Clients can add their own allowed domains" on public.allowed_domains;
create policy "Clients can add their own allowed domains"
  on public.allowed_domains for insert
  to authenticated
  with check (client_id in (select id from public.clients where user_id = (select auth.uid())));

drop policy if exists "Clients can remove their own allowed domains" on public.allowed_domains;
create policy "Clients can remove their own allowed domains"
  on public.allowed_domains for delete
  to authenticated
  using (client_id in (select id from public.clients where user_id = (select auth.uid())));

-- ---------------------------------------------------------------------------
-- Every client gets a key, and its website domain is allowed by default
-- ---------------------------------------------------------------------------

create or replace function public.set_up_public_access()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.api_keys (client_id) values (new.id) on conflict (client_id) do nothing;
  insert into public.allowed_domains (client_id, domain)
  select new.id, new.website_domain
  where new.website_domain !~ '\.localhost$' and new.website_domain !~ '^www\.'
  on conflict (client_id, domain) do nothing;
  return new;
end;
$$;

revoke all on function public.set_up_public_access() from public, anon, authenticated;

drop trigger if exists clients_set_up_public_access on public.clients;
create trigger clients_set_up_public_access
  after insert on public.clients
  for each row execute function public.set_up_public_access();

-- Existing clients.
insert into public.api_keys (client_id)
select id from public.clients
on conflict (client_id) do nothing;

insert into public.allowed_domains (client_id, domain)
select id, website_domain from public.clients
where website_domain !~ '\.localhost$' and website_domain !~ '^www\.'
on conflict (client_id, domain) do nothing;

-- ---------------------------------------------------------------------------
-- Rate limiting (server only)
-- ---------------------------------------------------------------------------

create table if not exists public.rate_limit_buckets (
  bucket text not null,
  window_start timestamptz not null,
  hits integer not null default 0,
  primary key (bucket, window_start)
);

comment on table public.rate_limit_buckets is 'Fixed-window request counters for rate limiting.';

revoke all on table public.rate_limit_buckets from anon, authenticated;
alter table public.rate_limit_buckets enable row level security;

-- Counts one request in the current window and returns whether it is within
-- the limit. Old windows are cleaned up now and then.
create or replace function public.hit_rate_limit(p_bucket text, p_limit integer, p_window_seconds integer)
returns boolean
language plpgsql
set search_path = ''
as $$
declare
  v_window timestamptz := to_timestamp(floor(extract(epoch from now()) / p_window_seconds) * p_window_seconds);
  v_hits integer;
begin
  insert into public.rate_limit_buckets as b (bucket, window_start, hits)
  values (p_bucket, v_window, 1)
  on conflict (bucket, window_start) do update set hits = b.hits + 1
  returning hits into v_hits;

  if random() < 0.01 then
    delete from public.rate_limit_buckets where window_start < now() - interval '1 hour';
  end if;

  return v_hits <= p_limit;
end;
$$;

revoke all on function public.hit_rate_limit(text, integer, integer) from public, anon, authenticated;
grant execute on function public.hit_rate_limit(text, integer, integer) to service_role;

-- ---------------------------------------------------------------------------
-- Rejected public requests
-- ---------------------------------------------------------------------------

create table if not exists public.public_api_rejections (
  id uuid primary key default gen_random_uuid(),
  -- Null when the key did not match any client.
  client_id uuid references public.clients (id) on delete cascade,
  reason text not null,
  origin text,
  created_at timestamptz not null default now(),

  constraint public_api_rejections_reason_valid check (
    reason in (
      'invalid_key',
      'assistant_paused',
      'missing_origin',
      'origin_not_allowed',
      'invalid_request',
      'ip_rate_limited',
      'key_rate_limited',
      'monthly_limit_reached'
    )
  ),
  constraint public_api_rejections_origin_length check (char_length(origin) <= 255)
);

comment on table public.public_api_rejections is 'Public chat requests that were refused, with the reason.';

create index if not exists public_api_rejections_client_idx
  on public.public_api_rejections (client_id, created_at desc);

revoke all on table public.public_api_rejections from anon, authenticated;
grant select (reason, origin, created_at) on table public.public_api_rejections to authenticated;

alter table public.public_api_rejections enable row level security;

drop policy if exists "Clients can view their own rejected requests" on public.public_api_rejections;
create policy "Clients can view their own rejected requests"
  on public.public_api_rejections for select
  to authenticated
  using (client_id in (select id from public.clients where user_id = (select auth.uid())));
